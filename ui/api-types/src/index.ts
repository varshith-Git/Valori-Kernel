// ── UI-layer view models — NOT wire types ──────────────────────────────────
//
// These describe values the UI's own Next.js BFF routes or React hooks add on
// top of a server response. They live here, clearly separated, so nobody is
// tempted to put them back into the wire model where they would read as
// something the node emits.

/** A `SearchResponse` after `ui/src/app/api/search/route.ts` stamps its own
 *  client-side receive time onto it. `queried_at` is generated by the BFF —
 *  the node never sends it. */
export type AnnotatedSearchResponse = SearchResponse & {
  /** ISO-8601 timestamp stamped by the UI's BFF route on receipt. Not server state. */
  queried_at?: string;
};

/** Cluster view state as `useCluster` computes it. `converged` is *derived* by
 *  comparing every member's `last_applied_index`; the node has no `converged`
 *  field and never claims convergence itself. */
export type ClusterView = {
  leaderId?: number;
  members: NonNullable<ClusterStatus["members"]>;
  /** Derived client-side: true when every member reports the same applied index. */
  converged: boolean;
};

/** A `SearchHit` after the UI's own metadata-sidecar lookup
 *  (`GET /api/meta?target_id=record:<id>`) attaches display text. Neither
 *  field is part of the node's `SearchHit` — they come from the sidecar, which
 *  is not replicated and not part of the audit chain. */
export type EnrichedSearchHit = SearchHit & {
  /** Chunk body text from the metadata sidecar. Client-side enrichment. */
  text?: string;
  /** Source document path from the metadata sidecar. Client-side enrichment. */
  source?: string;
};
