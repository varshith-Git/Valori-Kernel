// `@valori/api-types` — the ONE TypeScript model of the Valori Data Plane
// REST API v1.
//
// Before Phase API-2 there were two byte-identical, hand-written copies of a
// `types/valori.ts` (one under `ui/src/`, one under `ui/studio/src/`) that
// drifted from the wire and invented fields the server never emits
// (`SearchResponse.state_hash`, a hardcoded `ClusterStatus.converged`, a
// client-side `queried_at` presented as server state). This package replaces
// both. It is generated, not written:
//
//     ./scripts/generate-api-types.sh
//
// which runs `openapi-typescript` over `api/openapi/valori-v1.yaml` into
// `./src/valori-v1.ts`. That file is machine output — never hand-edit it.
//
// This index exists only to give the generated `components["schemas"][...]`
// index types the short, ergonomic aliases the UI already uses. Every alias
// below resolves into the generated tree, so a contract change that renames or
// removes a schema is a TypeScript error here rather than silent drift.

import type { components, paths, operations } from "./valori-v1.js";

export type { components, paths, operations };

type Schemas = components["schemas"];

// ── Wire models — every one of these is emitted by valori-node ──────────────

// Phase API-3.1: the contract is now generated end-to-end from Rust, so a
// schema's name in this file is the Rust type's name. Several aliases below
// therefore point at a different generated name than they did when the
// contract was hand-maintained — the alias (the left-hand side) is unchanged,
// so nothing downstream had to move.
//
// Aliases dropped in API-3.1 because the generated contract has no such
// schema and nothing in `ui/` imported them: `Metric`, `IndexKind`,
// `IndexType`, `IndexState`, `Consistency`, `InsertReceipt`, `EventLogProof`.
// `metric` and index-kind are plain strings on the wire, not closed enums, so
// there was never a schema to alias. If one is added later it will appear here
// as a generated name.

export type Error = Schemas["ApiError"];
export type ErrorCode = Schemas["ErrorCode"];

